#!/usr/bin/env node
/* Generates worker/catalogue.js from the shop data in index.html, so the order desk can
   list every product with its supplier links. Run after changing the shop:
       node worker/build-catalogue.js
   (build.py runs it automatically.) */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
// The first <script> holds the site data (a few constants, then `const SITE = {...};`).
const m = html.match(/<script>([\s\S]*?)<\/script>/);
if (!m || !/\nconst SITE = \{/.test(m[1])) { console.error('SITE block not found in index.html'); process.exit(1); }
const SITE = new Function(m[1] + '\nreturn SITE;')();

const ranges = SITE.shop.map(c => ({ id: c.id, name: c.name, groups: c.groups }));
const products = SITE.products.map(p => ({
  id: p.id,
  category: p.category || 'materials',
  group: p.group || p.brand,
  brand: p.brand,
  name: p.name,
  size: p.size || (Array.isArray(p.specs) && p.specs[0] ? p.specs[0].join(': ') : ''),
  link: p.link || ''
}));

const out = `/* Generated by worker/build-catalogue.js from index.html. Do not edit by hand. */
export const RANGES = ${JSON.stringify(ranges, null, 2)};
export const PRODUCTS = ${JSON.stringify(products, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, 'catalogue.js'), out);
console.log(`catalogue.js: ${products.length} products in ${ranges.length} ranges`);
